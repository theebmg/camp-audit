// ── Summary rich text (Oct 2026 brief, Part 2D) ──────────────────────────
//
// The summary is the only free-form prose on the report, and it needed bullets. Stored as a
// small subset of HTML and sanitised on the way in, because it is rendered into an email that
// goes to the board — anything not on this list is dropped rather than escaped, so a paste
// from Word cannot smuggle styling or script through.
const SUMMARY_ALLOWED_TAGS = new Set(['p', 'br', 'strong', 'b', 'em', 'i', 'ul', 'ol', 'li', 'a']);

// Inline styles, because Gmail strips <style> blocks and Outlook ignores much of what is left.
// Each tag carries its own appearance or it has none.
const SUMMARY_TAG_STYLE = {
  p: 'margin:0 0 10px;',
  ul: 'margin:0 0 10px;padding-left:22px;',
  ol: 'margin:0 0 10px;padding-left:22px;',
  li: 'margin:0 0 4px;',
  a: 'color:#3b5bdb;',
};

export function sanitizeSummaryHtml(raw) {
  if (!raw) return '';
  let html = String(raw);

  // Anything that can execute or load goes first, before the tag walk, so a malformed tag
  // cannot hide one of these inside it.
  html = html.replace(/<\s*(script|style|iframe|object|embed|link|meta)[\s\S]*?<\s*\/\s*\1\s*>/gi, '');
  html = html.replace(/<\s*(script|style|iframe|object|embed|link|meta)\b[^>]*>/gi, '');

  // A rejected <a> has to take its </a> with it, or the text keeps a stray closing tag. The
  // counter pairs them up rather than assuming they are adjacent.
  let droppedAnchors = 0;
  html = html.replace(/<\/?([a-zA-Z0-9]+)([^>]*)>/g, (match, tagRaw, attrs) => {
    const tag = tagRaw.toLowerCase();
    if (!SUMMARY_ALLOWED_TAGS.has(tag)) return '';          // drop the tag, keep its text
    const closing = match.startsWith('</');
    if (closing) {
      if (tag === 'a' && droppedAnchors > 0) { droppedAnchors -= 1; return ''; }
      return `</${tag}>`;
    }
    if (tag === 'a') {
      // Only http(s) and mailto survive, so javascript: and data: cannot ride in on a link.
      const href = (attrs.match(/href\s*=\s*["']([^"']*)["']/i) || [])[1] || '';
      const safe = /^(https?:|mailto:)/i.test(href.trim()) ? href.trim() : null;
      if (!safe) { droppedAnchors += 1; return ''; }
      return `<a href="${safe.replace(/"/g, '&quot;')}" style="${SUMMARY_TAG_STYLE.a}" target="_blank" rel="noopener noreferrer">`;
    }
    const style = SUMMARY_TAG_STYLE[tag];
    return style ? `<${tag} style="${style}">` : `<${tag}>`;
  });

  return html.trim();
}

// An existing plain-text summary still has to read correctly, and Ben's workaround of typing
// "- " at the start of a line becomes the bullets he was imitating (Part 2D). Two spaces or a
// tab before the dash nests one level, which is as deep as the editor goes.
export function plainSummaryToHtml(text) {
  if (!text) return '';
  if (/<(p|ul|ol|li|strong|em|b|i|a)\b/i.test(text)) return sanitizeSummaryHtml(text);  // already rich

  const esc = (t) => t.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
  const out = [];
  let list = null;          // 'ul' | 'ol' — the outer list, if one is open
  let nested = false;       // is a second-level list open?
  let liOpen = false;       // is an outer <li> still waiting to be closed?

  // A nested list is a CHILD of the item above it, not its sibling. That means the outer <li>
  // stays open until the nested list has been written and closed — writing </li> eagerly
  // produced <ul><li>..</li><ul>..</ul></ul>, which is invalid and which Outlook renders flat.
  const closeNested = () => { if (nested) { out.push('</ul>'); nested = false; } };
  const closeLi = () => { closeNested(); if (liOpen) { out.push('</li>'); liOpen = false; } };
  const closeList = () => { closeLi(); if (list) { out.push(`</${list}>`); list = null; } };

  for (const rawLine of String(text).split(/\r?\n/)) {
    const line = rawLine.replace(/\s+$/, '');
    if (!line.trim()) { closeList(); continue; }

    const bullet = line.match(/^(\s*)[-*•]\s+(.*)$/);
    const numbered = line.match(/^(\s*)\d+[.)]\s+(.*)$/);
    const m = bullet || numbered;
    if (m) {
      const want = bullet ? 'ul' : 'ol';
      const indented = m[1].length >= 2;
      if (indented) {
        if (!list) { out.push(`<${want} style="${SUMMARY_TAG_STYLE[want]}">`); list = want; }
        if (!liOpen) { out.push(`<li style="${SUMMARY_TAG_STYLE.li}">`); liOpen = true; }
        if (!nested) { out.push(`<ul style="${SUMMARY_TAG_STYLE.ul}">`); nested = true; }
        out.push(`<li style="${SUMMARY_TAG_STYLE.li}">${esc(m[2])}</li>`);
      } else {
        closeLi();
        if (list !== want) { closeList(); out.push(`<${want} style="${SUMMARY_TAG_STYLE[want]}">`); list = want; }
        out.push(`<li style="${SUMMARY_TAG_STYLE.li}">${esc(m[2])}`);
        liOpen = true;
      }
      continue;
    }
    closeList();
    out.push(`<p style="${SUMMARY_TAG_STYLE.p}">${esc(line)}</p>`);
  }
  closeList();
  return out.join('');
}

// For the plain-text half of the email, and anywhere a summary needs to be read without markup.
export function summaryHtmlToText(html) {
  if (!html) return '';
  return String(html)
    .replace(/<\/(p|div|li|ul|ol)>/gi, '\n')
    .replace(/<li[^>]*>/gi, '  - ')
    .replace(/<br\s*\/?>/gi, '\n')
    .replace(/<[^>]+>/g, '')
    .replace(/&nbsp;/g, ' ').replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>')
    .replace(/\n{3,}/g, '\n\n')
    .trim();
}

function moneyHeaderHtml(aggregates) {
  const byGroup = (g) => aggregates.filter((a) => a.GroupKey === g);
  const money = byGroup('money');
  const savings = byGroup('savings');
  if (!money.length && !savings.length) return '';
  const cell = (a) => `
    <td style="padding:12px 14px;border-left:4px solid #13432f;border-right:1px solid #c7d2dd;">
      <div style="color:#565c78;font-size:0.72rem;text-transform:uppercase;letter-spacing:0.05em;line-height:1.35;">${escapeHtml(a.Label)}</div>
      <div style="font-size:1.15rem;font-weight:700;color:#13432f;margin-top:2px;">${a.ValueNumeric != null ? fmtMoney(a.ValueNumeric) : escapeHtml(a.ValueText || '—')}</div>
      ${a.Note ? `<div style="color:#565c78;font-size:0.68rem;line-height:1.3;margin-top:3px;">${escapeHtml(a.Note)}</div>` : ''}
    </td>`;
  // Both rows must have the same number of cells or Outlook renders a ragged table — it does
  // not reflow a short row the way a browser does. The shorter row gets an empty filler cell.
  const cols = Math.max(money.length, savings.length, 1);
  const row = (cells) => {
    if (!cells.length) return '';
    const filler = '<td style="padding:12px 14px;"></td>'.repeat(cols - cells.length);
    return `<tr>${cells.map(cell).join('')}${filler}</tr>`;
  };
  return `
    <table role="presentation" bgcolor="#eef5f0" style="width:100%;border-collapse:collapse;background:#eef5f0;border:1px solid #c7d2dd;border-radius:10px;margin-bottom:18px;table-layout:fixed;">
      ${row(money)}
      ${row(savings)}
    </table>`;
}

// Photos under a report item (Part 2C).
//
// Grouped by the item, ordered before → during → after, and when an item has both a before and
// an after they go SIDE BY SIDE — before left, after right — stacking on a narrow screen. No
// attempt is made to pair particular shots: the brief says group by work order and order by
// stage, which is what a reader needs to follow.
//
// Laid out with a table and width percentages rather than flex or grid, because Outlook's
// rendering engine is Word and supports neither.
function photoFigureHtml(photo, { half = false } = {}) {
  const label = photo.SnapLabel || photo.Label || '';
  const width = half ? '100%' : '100%';
  return `
    <td style="width:${half ? '50%' : '100%'};padding:0 6px 10px;vertical-align:top;">
      <img src="cid:${escapeHtml(photo.Cid)}" alt="${escapeHtml(label)}"
           width="100%" style="width:${width};max-width:100%;height:auto;display:block;border-radius:8px;border:1px solid #c7d2dd;" />
      ${label ? `<div style="color:#565c78;font-size:0.8rem;margin-top:4px;line-height:1.3;">${escapeHtml(label)}</div>` : ''}
    </td>`;
}

function itemPhotosHtml(photos) {
  if (!photos || !photos.length) return '';
  const rows = [];
  // A before and an after sit together; anything else runs full width.
  const before = photos.filter((p) => p.StageOrder === 1);
  const after = photos.filter((p) => p.StageOrder === 3);
  const rest = photos.filter((p) => p.StageOrder !== 1 && p.StageOrder !== 3);
  const pairs = Math.min(before.length, after.length);
  for (let i = 0; i < pairs; i++) {
    rows.push(`<tr>${photoFigureHtml(before[i], { half: true })}${photoFigureHtml(after[i], { half: true })}</tr>`);
  }
  for (const p of [...before.slice(pairs), ...rest, ...after.slice(pairs)]) {
    rows.push(`<tr>${photoFigureHtml(p)}</tr>`);
  }
  return `
    <table role="presentation" width="100%" style="width:100%;border-collapse:collapse;margin:8px 0 4px;">
      ${rows.join('')}
    </table>`;
}

// "Started 9/5 · Completed 9/23", or "Completed 9/23" when it began and finished the same day —
// a span of one day is not a span, and printing both halves of it reads as a mistake.
function itemDatesText(it) {
  if (!it.SnapStartDate) return it.SnapDate ? fmtDate(it.SnapDate) : null;
  if (!it.SnapDate) return `Started ${fmtDate(it.SnapStartDate)} · In progress`;
  if (String(it.SnapStartDate) === String(it.SnapDate)) return `Completed ${fmtDate(it.SnapDate)}`;
  return `Started ${fmtDate(it.SnapStartDate)} · Completed ${fmtDate(it.SnapDate)}`;
}

// A job line nested under its work order. Deliberately sparse: the parent already says where
// the work was and that it is done, so repeating the work order's name, the location and the
// status on every line is noise the board has to read past. Title, date, cost — nothing else.
// A $0 line is a line with no money against it, so the figure is left off rather than printed
// as a meaningless zero.
// "Funded by Ben", or "Ben $800 · Camp $440" when more than one source paid.
//
// showFunding: 'off' prints nothing; 'non_camp' prints only money that did NOT come from camp
// funds, because the board's question is what a job cost CAMP and camp money needs no tag;
// 'all' labels everything.
//
// Returns null rather than an empty string when there is nothing to say, so callers can drop
// the separator too.
function fundingTagText(it, showFunding) {
  if (showFunding === 'off') return null;
  const all = Array.isArray(it.SnapFunding) ? it.SnapFunding.filter((f) => f && f.Amount) : [];
  if (!all.length) return null;
  const shown = showFunding === 'all' ? all : all.filter((f) => f.IsCamp === false);
  if (!shown.length) return null;
  // One source paying for the whole thing reads as a sentence; a split reads as figures.
  if (shown.length === 1 && shown.length === all.length) return `Funded by ${shown[0].Source}`;
  return shown.map((f) => `${f.Source} ${fmtMoney(f.Amount)}`).join(' · ');
}

function nestedLineHtml(it, showHours = false, showFunding = 'non_camp') {
  // No date: every line under a work order happened inside the reporting period, and the work
  // order above already carries the span. Repeating it on each line was the noisiest thing left.
  const bits = [
    showHours && it.SnapHours != null ? fmtHours(it.SnapHours) : null,
    it.SnapCost ? fmtMoney(it.SnapCost) : null,
    // "est. on open items only" — the same rule the work order row above it uses.
    !it.SnapCost && !it.SnapDate && it.SnapEstCost ? `~${fmtMoney(it.SnapEstCost)} est.` : null,
    fundingTagText(it, showFunding),
  ].filter(Boolean);
  return `
    <div style="padding:4px 0;font-size:0.92rem;color:#474d66;">
      ${escapeHtml(it.SnapTitle || '(untitled)')}${bits.length ? `<span style="color:#565c78;"> · ${escapeHtml(bits.join(' · '))}</span>` : ''}
    </div>`;
}

// The indent rail. A left border on a td is one of the few indent mechanisms Word's rendering
// engine honours, so Outlook shows the same connecting line every other client does — a
// margin-left div or a CSS border on a div would simply be dropped there.
function nestedBlockHtml(innerHtml) {
  if (!innerHtml) return '';
  return `
    <table role="presentation" width="100%" cellpadding="0" cellspacing="0" border="0"
           style="width:100%;border-collapse:collapse;margin:2px 0 6px;">
      <tr>
        <td width="14" style="width:14px;"></td>
        <td style="border-left:3px solid #1a5c40;padding:2px 0 2px 12px;">${innerHtml}</td>
      </tr>
    </table>`;
}

// What a job has left, under an open work order only. Grey, and after the finished lines:
// the board reads what happened first and what is outstanding second.
function stillToDoHtml(it) {
  const open = Array.isArray(it.SnapOpenLines) ? it.SnapOpenLines.filter(Boolean) : [];
  if (!open.length) return '';
  return `
    <div style="padding:5px 0 2px;font-size:0.87rem;color:#7a4a10;">
      <span style="font-weight:700;">Still to do:</span> ${escapeHtml(open.join(' · '))}
    </div>`;
}

function itemLineHtml(it, showHours = false, opts = {}, showFunding = 'non_camp') {
  // Dates read as a span rather than a single stamp (decisions §7): when something started
  // and whether it has finished is more use to a board than one undated figure.
  const dates = itemDatesText(it);
  // Money: actual only, and only when there is one. An estimate is labelled "est." and shown
  // on open work alongside it — never instead of it and never summed (decisions §2, §3).
  // Spend against estimate reads as one fact, not two: "$800 spent of ~$1,540 est." says where
  // a job has got to in a way that "$800 · ~$1,540 est." does not. Either half alone still
  // prints on its own.
  const money = it.SnapCost != null ? fmtMoney(it.SnapCost) : null;
  const est = it.SnapEstCost != null && !it.SnapDate ? `~${fmtMoney(it.SnapEstCost)} est.` : null;
  const spend = money && est ? `${money} spent of ${est}` : (money || est);
  const funding = fundingTagText(it, showFunding);
  const bits = [
    it.SnapAssetName, it.SnapStatus, dates,
    showHours && it.SnapHours != null ? fmtHours(it.SnapHours) : null,
    spend, funding,
  ].filter(Boolean);
  // The em-dash suffix is for things the detail line does not already say. Printing the
  // asset there as well gave "Front Gate Repair — Red Gate" above "Red Gate · Done · …",
  // and an admin task's category turned into "Fixed NVR Hard Drive — Other", which is noise
  // to a board reader (fix 8).
  // An admin task's subtitle only ever carried its category, which is internal filing rather
  // than something the board needs, so it is not printed at all. Existing snapshot rows still
  // hold it — the upsert's COALESCE cannot clear a stored value — so the guard lives here as
  // well as at the source.
  const suffix = it.SnapSubtitle
    && it.SnapSubtitle !== it.SnapAssetName
    && it.ItemType !== 'admin_task'
    ? it.SnapSubtitle : null;
  return `
    <div style="border-bottom:1px solid #c7d2dd;padding:9px 0;">
      <div><strong>${escapeHtml(it.SnapTitle || '(untitled)')}</strong>${suffix ? ` <span style="color:#565c78;">— ${escapeHtml(suffix)}</span>` : ''}</div>
      ${bits.length ? `<div style="color:#565c78;font-size:0.85rem;">${escapeHtml(bits.join(' · '))}</div>` : ''}
      ${it.SnapProgress && !opts.hideProgress ? `<div style="color:#565c78;font-size:0.85rem;">${escapeHtml(it.SnapProgress)}</div>` : ''}
      ${opts.nested || ''}
      ${stillToDoHtml(it)}
      ${itemPhotosHtml(it.Photos)}
      ${it.ReportNote ? `<div style="margin-top:4px;font-size:0.9rem;">${escapeHtml(it.ReportNote)}</div>` : ''}
    </div>`;
}

// A summary work order prints one line and swallows its job lines; an itemized one
// prints its lines instead. Summary is the default for every WO (§6).
function sectionHtml(section, items, showHours = false, showFunding = 'non_camp') {
  if (!items.some((i) => i.Section === section && i.Included)) return '';
  // One rule, shared with the footer, so a section subtotal and the grand total can never
  // disagree about what counts again.
  const visible = visibleItems(items).filter((i) => i.Section === section);
  if (!visible.length) return '';
  const counted = totalledItems(items).filter((i) => i.Section === section);
  const hours = counted.reduce((t, i) => t + (i.SnapHours || 0), 0);
  const cost = counted.reduce((t, i) => t + (i.SnapCost || 0), 0);
  const sub = [showHours && hours ? fmtHours(hours) : null, cost ? fmtMoney(cost) : null].filter(Boolean).join(' · ');

  // The count is of PIECES OF WORK — work orders, admin tasks, findings — not of job lines. A
  // thirteen-line renovation is one thing the board decided to do, not thirteen. Same set the
  // subtotal is made from, so the count and the money can never describe different things.
  const orphanLines = counted.filter((i) => i.ItemType === 'job_line');
  const count = counted.length;

  // Each parent, with its own lines nested beneath it in document order.
  const rendered = [];
  for (const it of visible) {
    if (it.ItemType === 'job_line' && orphanLines.includes(it)) { rendered.push(itemLineHtml(it, showHours, {}, showFunding)); continue; }
    if (it.ItemType === 'job_line') continue;             // printed under its work order below
    if (it.ItemType !== 'work_order') { rendered.push(itemLineHtml(it, showHours, {}, showFunding)); continue; }
    const lines = visible.filter((l) => l.ItemType === 'job_line' && l.ParentWorkOrderId === it.ItemId);
    const nested = nestedBlockHtml(lines.map((l) => nestedLineHtml(l, showHours, showFunding)).join(''));
    // An itemized work order's lines say what was completed, so the roll-up sentence that says
    // the same thing in prose is redundant directly above them.
    rendered.push(itemLineHtml(it, showHours, { nested, hideProgress: lines.length > 0 }, showFunding));
  }

  return `
    <h2 style="margin:26px 0 6px;font-size:1.05rem;color:#13432f;border-top:2px solid #13432f;padding-top:12px;text-transform:uppercase;letter-spacing:0.04em;">
      ${escapeHtml(SECTION_TITLES[section] || section)}
      <span style="color:#565c78;font-weight:400;font-size:0.85rem;text-transform:none;letter-spacing:0;"> — ${count} item(s)${sub ? ` · ${sub}` : ''}</span>
    </h2>
    ${rendered.join('')}`;
}

// What the reader can actually see: included, minus the job lines their work order is
// summarising away. sectionHtml() has always applied this to its own subtotals; the grand
// footer did not, so it counted and totalled 15 rows nobody could see.
function visibleItems(items) {
  const summaryWoIds = new Set(
    items.filter((i) => i.Included && i.ItemType === 'work_order' && i.DisplayMode === 'summary')
      .map((i) => i.ItemId)
  );
  return items.filter((i) => i.Included
    && !(i.ItemType === 'job_line' && summaryWoIds.has(i.ParentWorkOrderId)));
}

// What the money is counted from — which is NOT the same as what is printed. A work order's row
// carries the roll-up of its own lines, so adding both the row and the lines beneath it counts
// the same money twice: an itemized job showing $800 on the row and $800 on the line it came
// from put $1,600 in the total. Count the work order, print the detail.
//
// A job line whose work order is not on the report has nobody to roll it up, so it counts for
// itself. Admin tasks and findings always count for themselves.
function totalledItems(items) {
  const visible = visibleItems(items);
  const woIds = new Set(visible.filter((i) => i.ItemType === 'work_order').map((i) => i.ItemId));
  return visible.filter((i) => i.ItemType !== 'job_line' || !woIds.has(i.ParentWorkOrderId));
}

