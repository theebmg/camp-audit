// Renders report data (from reportData.js) into HTML and plain text. Kept
// separate from data-building so "what a report contains" and "how it looks" can
// change independently. HTML uses inline styles only — email clients and the
// print stylesheet both need that, not an external stylesheet.

function escapeHtml(s) {
  return String(s ?? '').replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
}

// Report data may carry either ISO date strings or raw `pg` driver Date
// objects straight from `date`/`timestamp` columns — normalize both to a
// string before slicing.
const isoStr = (v) => (v instanceof Date ? v.toISOString() : String(v || ''));
const fmtDate = (iso) => isoStr(iso).slice(0, 10);
const fmtMoney = (n) => (n == null ? '—' : `$${Number(n).toLocaleString()}`);

export function htmlShell(title, subtitle, bodyHtml) {
  return `<!doctype html>
<html><head><meta charset="utf-8"><title>${escapeHtml(title)}</title></head>
<body style="margin:0;padding:24px;background:#f6f7fb;font-family:-apple-system,Segoe UI,Roboto,sans-serif;color:#1a1d29;">
  <div style="max-width:680px;margin:0 auto;background:#ffffff;border:1px solid #e5e7f0;border-radius:16px;padding:28px;">
    <h1 style="margin:0 0 4px;font-size:1.4rem;">🏕️ ${escapeHtml(title)}</h1>
    <div style="color:#6b7086;font-size:0.9rem;margin-bottom:20px;">${escapeHtml(subtitle)}</div>
    ${bodyHtml}
    <div style="margin-top:28px;padding-top:14px;border-top:1px solid #e5e7f0;color:#9298b0;font-size:0.78rem;">
      Generated by Camp Sychar Audit — ${escapeHtml(new Date().toISOString().slice(0, 16).replace('T', ' '))}
    </div>
  </div>
</body></html>`;
}

function countPillsHtml(items, key) {
  return items.map((s) => `
    <div style="display:inline-block;background:#f0f2fb;border-radius:12px;padding:10px 16px;margin:0 8px 8px 0;">
      <div style="font-size:1.1rem;font-weight:800;">${s.count}</div>
      <div style="font-size:0.78rem;color:#6b7086;">${escapeHtml(s[key])}</div>
    </div>`).join('');
}

function boardListRowsHtml(items) {
  return items.map((i) => `
    <tr>
      <td style="padding:7px 10px;border-bottom:1px solid #eef0f6;white-space:nowrap;">${escapeHtml(fmtDate(i.scheduledDate || i.dateCompleted))}</td>
      <td style="padding:7px 10px;border-bottom:1px solid #eef0f6;">${escapeHtml(i.title)}${i.jobLineTitle ? ` — ${escapeHtml(i.jobLineTitle)}` : ''}</td>
      <td style="padding:7px 10px;border-bottom:1px solid #eef0f6;">${escapeHtml(i.assetName || '—')}</td>
      <td style="padding:7px 10px;border-bottom:1px solid #eef0f6;">${i.priority ? escapeHtml(i.priority) : fmtMoney(i.cost)}</td>
    </tr>`).join('');
}

// Board / monthly report: current open-WO snapshot (status/priority/funding),
// plus what happened and what's next relative to today — regardless of the
// period bounds, which only scope the "Completed" section (a board wants to
// know what's overdue/upcoming right now, not just within the report month).
export function renderBoardReportHtml({ periodStart, periodEnd, statusCounts, priorityCounts, fundingSourceTotals, completed, upcoming, overdue }) {
  const fundingRowsHtml = fundingSourceTotals.map((f) => `
    <tr><td style="padding:7px 10px;border-bottom:1px solid #eef0f6;">${escapeHtml(f.label)}</td>
        <td style="padding:7px 10px;border-bottom:1px solid #eef0f6;text-align:right;">${fmtMoney(f.total)}</td></tr>`).join('');
  const listTable = (items, emptyLabel) => `
    <table style="width:100%;border-collapse:collapse;margin-bottom:20px;">
      ${boardListRowsHtml(items) || `<tr><td style="padding:14px;color:#6b7086;">${escapeHtml(emptyLabel)}</td></tr>`}
    </table>`;
  return htmlShell('Board Report', `${periodStart} to ${periodEnd}`, `
    <h3 style="margin:0 0 8px;font-size:1rem;">Open Work Orders by Status</h3>
    <div>${countPillsHtml(statusCounts, 'status') || '<span style="color:#6b7086;">None open.</span>'}</div>
    <h3 style="margin:20px 0 8px;font-size:1rem;">By Priority</h3>
    <div>${countPillsHtml(priorityCounts, 'priority') || '<span style="color:#6b7086;">None open.</span>'}</div>
    <h3 style="margin:20px 0 8px;font-size:1rem;">Outstanding Cost by Funding Source</h3>
    <table style="width:100%;border-collapse:collapse;margin-bottom:20px;">${fundingRowsHtml || '<tr><td style="padding:14px;color:#6b7086;">No outstanding cost.</td></tr>'}</table>
    <h3 style="margin:0 0 8px;font-size:1rem;">Completed This Period (${completed.length})</h3>
    ${listTable(completed, 'Nothing completed this period.')}
    <h3 style="margin:0 0 8px;font-size:1rem;">Overdue (${overdue.length})</h3>
    ${listTable(overdue, 'Nothing overdue.')}
    <h3 style="margin:0 0 8px;font-size:1rem;">Upcoming (${upcoming.length})</h3>
    ${listTable(upcoming, 'Nothing scheduled.')}
  `);
}

export function renderBoardReportText({ periodStart, periodEnd, statusCounts, priorityCounts, fundingSourceTotals, completed, upcoming, overdue }) {
  const lines = ['CAMP SYCHAR — BOARD REPORT', `${periodStart} to ${periodEnd}`, ''];
  lines.push('Open Work Orders by Status:');
  statusCounts.forEach((s) => lines.push(`  ${s.status}: ${s.count}`));
  if (!statusCounts.length) lines.push('  None open.');
  lines.push('', 'By Priority:');
  priorityCounts.forEach((p) => lines.push(`  ${p.priority}: ${p.count}`));
  if (!priorityCounts.length) lines.push('  None open.');
  lines.push('', 'Outstanding Cost by Funding Source:');
  fundingSourceTotals.forEach((f) => lines.push(`  ${f.label}: ${fmtMoney(f.total)}`));
  if (!fundingSourceTotals.length) lines.push('  None.');
  lines.push('', `Completed This Period (${completed.length}):`);
  completed.forEach((c) => lines.push(`  ${fmtDate(c.dateCompleted)}  ${c.title}${c.assetName ? ` (${c.assetName})` : ''} — ${fmtMoney(c.cost)}`));
  if (!completed.length) lines.push('  None.');
  lines.push('', `Overdue (${overdue.length}):`);
  overdue.forEach((o) => lines.push(`  ${fmtDate(o.scheduledDate)}  ${o.title}${o.jobLineTitle ? ` — ${o.jobLineTitle}` : ''}${o.assetName ? ` (${o.assetName})` : ''} [${o.priority}]`));
  if (!overdue.length) lines.push('  None.');
  lines.push('', `Upcoming (${upcoming.length}):`);
  upcoming.forEach((u) => lines.push(`  ${fmtDate(u.scheduledDate)}  ${u.title}${u.jobLineTitle ? ` — ${u.jobLineTitle}` : ''}${u.assetName ? ` (${u.assetName})` : ''} [${u.priority}]`));
  if (!upcoming.length) lines.push('  None.');
  return lines.join('\n');
}

export function renderForwardFocusHtml({ items, total }) {
  const rowsHtml = items.map((i) => `
    <tr>
      <td style="padding:7px 10px;border-bottom:1px solid #eef0f6;">${escapeHtml(i.kind === 'workOrder' ? 'Work Order' : 'Condition Finding')}</td>
      <td style="padding:7px 10px;border-bottom:1px solid #eef0f6;">${escapeHtml(i.title)}${i.jobLineTitle ? ` — ${escapeHtml(i.jobLineTitle)}` : ''}</td>
      <td style="padding:7px 10px;border-bottom:1px solid #eef0f6;">${escapeHtml(i.assetName || '—')}</td>
      <td style="padding:7px 10px;border-bottom:1px solid #eef0f6;">${fmtMoney(i.cost)}${i.costBasis === 'historical average' ? ' <span style="color:#6b7086;font-size:0.75rem;">(hist. avg)</span>' : ''}</td>
    </tr>`).join('');
  return htmlShell('Forward Focus', `Board-flagged items · ${items.length} item(s) · ${fmtMoney(total)} total`, `
    <table style="width:100%;border-collapse:collapse;">
      <tr style="text-align:left;font-size:0.78rem;color:#6b7086;text-transform:uppercase;">
        <th style="padding:7px 10px;">Type</th><th>Item</th><th>Asset</th><th>Est. Cost</th>
      </tr>
      ${rowsHtml || '<tr><td style="padding:14px;color:#6b7086;">Nothing flagged for the board right now.</td></tr>'}
    </table>
  `);
}

export function renderForwardFocusText({ items, total }) {
  const lines = ['CAMP SYCHAR — FORWARD FOCUS', `Board-flagged items — ${items.length} item(s), ${fmtMoney(total)} total`, ''];
  items.forEach((i) => lines.push(`${i.kind === 'workOrder' ? 'WO' : 'CF'}  ${i.title}${i.assetName ? ` (${i.assetName})` : ''} — ${fmtMoney(i.cost)}${i.costBasis === 'historical average' ? ' (hist. avg)' : ''}`));
  if (!items.length) lines.push('Nothing flagged for the board right now.');
  return lines.join('\n');
}

// "Work Performed in a Date Range" (§6.2.1) — grouped by building, images
// embed (After photos, capped per WO — see getReportImagesForJobLines),
// documents would link but this report only ever shows images by
// construction (image-kind filter is in the raw-data query).
export function renderWorkPerformedHtml({ from, to, buildings, totalLines, totalCost, totalHours }) {
  const buildingHtml = (b) => `
    <h3 style="margin:20px 0 4px;font-size:1rem;">${escapeHtml(b.location)} <span style="color:#6b7086;font-weight:400;font-size:0.85rem;">— ${fmtMoney(b.totalCost)} · ${b.totalHours}h</span></h3>
    ${b.lines.map((l) => `
      <div style="border-bottom:1px solid #eef0f6;padding:10px 0;">
        <div><strong>${escapeHtml(l.title)}</strong> — WO ${escapeHtml(l.woNumber || l.workOrderId)}${l.assetName ? ` · ${escapeHtml(l.assetName)}` : ''}</div>
        <div style="color:#6b7086;font-size:0.85rem;">${escapeHtml(fmtDate(l.completedDate))} · ${fmtMoney(l.cost)}${l.hours ? ` · ${l.hours}h` : ''}</div>
        ${l.correction ? `<div style="font-size:0.9rem;margin-top:2px;">${escapeHtml(l.correction)}</div>` : ''}
        ${l.images.length ? `<div style="margin-top:6px;">${l.images.map((img) => `<img src="${escapeHtml(img.Url)}" alt="${escapeHtml(img.Caption || '')}" style="max-width:220px;max-height:220px;border-radius:8px;margin:0 6px 6px 0;" />`).join('')}</div>` : ''}
      </div>`).join('')}`;
  return htmlShell('Work Performed', `${from} to ${to} · ${totalLines} line(s) · ${fmtMoney(totalCost)} · ${totalHours}h`, `
    ${buildings.map(buildingHtml).join('') || '<p style="color:#6b7086;">No completed work in this range.</p>'}
  `);
}
export function renderWorkPerformedText({ from, to, buildings, totalLines, totalCost, totalHours }) {
  const lines = ['CAMP SYCHAR — WORK PERFORMED', `${from} to ${to} — ${totalLines} line(s), ${fmtMoney(totalCost)}, ${totalHours}h`, ''];
  buildings.forEach((b) => {
    lines.push(`${b.location} — ${fmtMoney(b.totalCost)}, ${b.totalHours}h`);
    b.lines.forEach((l) => lines.push(`  ${fmtDate(l.completedDate)}  ${l.title} (WO ${l.woNumber || l.workOrderId}${l.assetName ? `, ${l.assetName}` : ''}) — ${fmtMoney(l.cost)}`));
  });
  if (!buildings.length) lines.push('No completed work in this range.');
  return lines.join('\n');
}

// "Deferred Maintenance Backlog" (§6.2.2) — grouped by severity, worst
// first, each group's dollar total.
export function renderDeferredBacklogHtml({ groups, totalCost, totalCount }) {
  const groupHtml = (g) => `
    <h3 style="margin:20px 0 4px;font-size:1rem;">${escapeHtml(g.severity)} <span style="color:#6b7086;font-weight:400;font-size:0.85rem;">— ${fmtMoney(g.totalCost)}</span></h3>
    <table style="width:100%;border-collapse:collapse;margin-bottom:10px;">
      ${g.items.map((i) => `
        <tr>
          <td style="padding:6px 10px;border-bottom:1px solid #eef0f6;">${escapeHtml(i.title)}</td>
          <td style="padding:6px 10px;border-bottom:1px solid #eef0f6;">${escapeHtml(i.assetName || i.locationName || '—')}</td>
          <td style="padding:6px 10px;border-bottom:1px solid #eef0f6;">${escapeHtml(i.deferredReason || '—')}${i.revisitDate ? ` — revisit ${fmtDate(i.revisitDate)}` : ''}</td>
          <td style="padding:6px 10px;border-bottom:1px solid #eef0f6;text-align:right;">${fmtMoney(i.cost)}</td>
        </tr>`).join('')}
    </table>`;
  return htmlShell('Deferred Maintenance Backlog', `${totalCount} deferred finding(s) · ${fmtMoney(totalCost)} total`, `
    ${groups.map(groupHtml).join('') || '<p style="color:#6b7086;">Nothing deferred right now.</p>'}
  `);
}
export function renderDeferredBacklogText({ groups, totalCost, totalCount }) {
  const lines = ['CAMP SYCHAR — DEFERRED MAINTENANCE BACKLOG', `${totalCount} deferred finding(s) — ${fmtMoney(totalCost)} total`, ''];
  groups.forEach((g) => {
    lines.push(`${g.severity} — ${fmtMoney(g.totalCost)}`);
    g.items.forEach((i) => lines.push(`  ${i.title} (${i.assetName || i.locationName || '—'}) — ${fmtMoney(i.cost)}${i.deferredReason ? ` — ${i.deferredReason}` : ''}${i.revisitDate ? `, revisit ${fmtDate(i.revisitDate)}` : ''}`));
  });
  if (!groups.length) lines.push('Nothing deferred right now.');
  return lines.join('\n');
}

// Turns a plain-text message (a Requester notification, a free-form message
// from the Requests inbox) into a simple branded HTML body — same htmlShell
// as every other report email, just a preformatted paragraph instead of a
// table. Not for structured reports; those build their own bodyHtml.
export function renderPlainEmailHtml(subject, text) {
  return htmlShell(subject, '', `<div style="white-space:pre-wrap;line-height:1.5;">${escapeHtml(text)}</div>`);
}
